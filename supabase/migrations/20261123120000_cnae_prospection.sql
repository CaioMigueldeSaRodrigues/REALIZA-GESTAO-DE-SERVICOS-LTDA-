-- REALIZA: Prospecção comercial ativa a partir de estabelecimento/CNAE em MG.
-- Apenas a equipe comercial acessa esses dados; não há publicação anônima.
begin;
create table if not exists public.commercial_prospects (
 id uuid primary key default gen_random_uuid(),
 cnpj text not null unique check(cnpj ~ '^[0-9A-Z]{12}[0-9]{2}$'),
 name text not null check(char_length(trim(name))>1),
 trade_name text,
 cnae text not null check(cnae ~ '^[0-9]{2,7}$'),
 city text,
 state text not null default 'MG' check(state='MG'),
 opened_on date not null,
 snapshot_on date,
 registration_status text,
 status text not null default 'novo' check(status in ('novo','em_qualificacao','contatado','convertido','descartado')),
 notes text not null default '' check(char_length(notes)<=3000),
 source text not null default 'bigquery_cnpj',
 created_by uuid not null references auth.users(id),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.commercial_prospects enable row level security;
grant select,insert,update on public.commercial_prospects to authenticated;
create policy prospects_commercial_read on public.commercial_prospects for select to authenticated
 using ((select private.has_any_role(array['admin','gestor','comercial','analista'])));
create policy prospects_commercial_insert on public.commercial_prospects for insert to authenticated
 with check (
   state='MG' and created_by=(select auth.uid())
   and (select private.has_any_role(array['admin','gestor','comercial']))
 );
create policy prospects_commercial_update on public.commercial_prospects for update to authenticated
 using ((select private.has_any_role(array['admin','gestor','comercial'])))
 with check (
   state='MG' and (select private.has_any_role(array['admin','gestor','comercial']))
 );

create table if not exists private.commercial_search_audit (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 cnae text not null,
 created_at timestamptz not null default now()
);
revoke all on private.commercial_search_audit from public,anon,authenticated;
create index commercial_search_rate_limit on private.commercial_search_audit(user_id,created_at desc);

create function public.reserve_commercial_search(p_cnae text)
returns boolean language plpgsql security definer set search_path='' as $$
declare recent_count int;
begin
 if auth.uid() is null or
    not private.has_any_role(array['admin','gestor','comercial']) then
   raise exception 'Sem permissão para prospecção ativa';
 end if;
 if p_cnae !~ '^[0-9]{2,7}$' then
   raise exception 'Informe CNAE numérico de 2 a 7 dígitos';
 end if;
 -- Serialize same-user quota checks to avoid parallel requests evading the limit.
 perform pg_advisory_xact_lock(hashtext(auth.uid()::text));
 select count(*) into recent_count from private.commercial_search_audit
 where user_id=auth.uid() and created_at>now()-interval '1 hour';
 if recent_count>=5 then
   raise exception 'Limite de 5 pesquisas por hora atingido; consulte resultados já salvos';
 end if;
 insert into private.commercial_search_audit(user_id,cnae) values(auth.uid(),p_cnae);
 return true;
end;$$;
revoke all on function public.reserve_commercial_search(text) from public,anon;
grant execute on function public.reserve_commercial_search(text) to authenticated;
commit;