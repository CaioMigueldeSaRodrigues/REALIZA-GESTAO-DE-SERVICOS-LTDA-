-- REALIZA / Levantamento para parametrização da plataforma operacional.
-- Uma ficha única, rascunhos parciais, revisão auditável e saída para BI/RAG.
begin;
create table public.company_operational_survey (
 id uuid primary key default gen_random_uuid(),
 company_code text not null default 'realiza' unique check(company_code='realiza'),
 answers jsonb not null default '{}'::jsonb
   check(jsonb_typeof(answers)='object' and pg_column_size(answers)<=65536),
 status text not null default 'rascunho' check(status in ('rascunho','enviado')),
 revision integer not null default 1 check(revision>=1),
 updated_by uuid not null references auth.users(id),
 submitted_at timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table public.company_operational_survey_history (
 id bigint generated by default as identity primary key,
 survey_id uuid not null references public.company_operational_survey(id) on delete cascade,
 revision integer not null,
 status text not null,
 answers jsonb not null,
 actor_id uuid references auth.users(id),
 recorded_at timestamptz not null default now(),
 unique(survey_id,revision)
);
alter table public.company_operational_survey enable row level security;
alter table public.company_operational_survey_history enable row level security;

grant select,insert,update on public.company_operational_survey to authenticated;
grant select on public.company_operational_survey_history to authenticated;
create policy operational_survey_read on public.company_operational_survey
 for select to authenticated using (
  (select private.has_any_role(array['admin','gestor','analista']))
 );
create policy operational_survey_insert on public.company_operational_survey
 for insert to authenticated with check (
  company_code='realiza' and
  (select private.has_any_role(array['admin','gestor']))
 );
create policy operational_survey_update on public.company_operational_survey
 for update to authenticated using (
  (select private.has_any_role(array['admin','gestor']))
 ) with check (
  company_code='realiza' and
  (select private.has_any_role(array['admin','gestor']))
 );
create policy operational_survey_history_read on public.company_operational_survey_history
 for select to authenticated using (
  (select private.has_any_role(array['admin','gestor','analista']))
 );

create function private.validate_operational_survey()
 returns trigger language plpgsql set search_path='' as $$
declare full_name text; cities text; base_city text; fleet_total text; capacity text;
begin
 if auth.uid() is null then
  raise exception 'Apenas usuários autenticados podem salvar o levantamento';
 end if;
 if TG_OP='UPDATE' then
  if new.id is distinct from old.id or new.company_code is distinct from old.company_code then
   raise exception 'Identificador da empresa não pode ser alterado';
  end if;
  new.revision=old.revision+1;
 else
  new.revision=1;
 end if;
 new.updated_by=auth.uid();
 new.updated_at=now();
 if new.status='enviado' then
  full_name=trim(coalesce(new.answers #>> '{contact,name}',''));
  base_city=trim(coalesce(new.answers #>> '{contact,base_city}',''));
  cities=trim(coalesce(new.answers #>> '{coverage,cities}',''));
  fleet_total=trim(coalesce(new.answers #>> '{fleet,total}',''));
  capacity=trim(coalesce(new.answers #>> '{capacity,max_daily_m3}',''));
  if char_length(full_name)<3 or char_length(base_city)<2 or
     char_length(cities)<2 or fleet_total !~ '^[0-9]+$' or
     fleet_total::numeric<=0 or capacity !~ '^[0-9]+([.][0-9]+)?$'
     or capacity::numeric<=0 then
    raise exception 'Preencha responsável, cidade-base, área de atuação, caminhões e capacidade diária antes de concluir';
  end if;
  new.submitted_at=now();
 else
  new.submitted_at=null;
 end if;
 return new;
end;$$;
create trigger company_operational_survey_validate
 before insert or update on public.company_operational_survey
 for each row execute function private.validate_operational_survey();

create function private.archive_operational_survey()
 returns trigger language plpgsql security definer set search_path='' as $$
begin
 insert into public.company_operational_survey_history
  (survey_id,revision,status,answers,actor_id)
 values(new.id,new.revision,new.status,new.answers,new.updated_by);
 if new.status='enviado' then
  insert into public.automation_queue(event_type,entity_id,payload)
  values('levantamento_operacional_enviado',new.id,
    jsonb_build_object('revision',new.revision,'company_code',new.company_code));
 end if;
 return new;
end;$$;
revoke all on function private.archive_operational_survey() from public,anon,authenticated;
create trigger company_operational_survey_archive
 after insert or update on public.company_operational_survey
 for each row execute function private.archive_operational_survey();

create view public.bi_operational_capacity
 with (security_invoker=true) as
 select company_code,status,revision,submitted_at,
  nullif(answers #>> '{contact,base_city}','') as base_city,
  nullif(answers #>> '{coverage,cities}','') as covered_cities,
  case when (answers #>> '{fleet,total}') ~ '^[0-9]+$'
       then (answers #>> '{fleet,total}')::integer else null end as fleet_total,
  case when (answers #>> '{fleet,available}') ~ '^[0-9]+$'
       then (answers #>> '{fleet,available}')::integer else null end as fleet_available,
  case when (answers #>> '{capacity,max_daily_m3}') ~ '^[0-9]+([.][0-9]+)?$'
       then (answers #>> '{capacity,max_daily_m3}')::numeric else null end as max_daily_m3,
  case when (answers #>> '{capacity,max_deliveries_day}') ~ '^[0-9]+$'
       then (answers #>> '{capacity,max_deliveries_day}')::integer else null end as max_deliveries_day
 from public.company_operational_survey
 where status='enviado';
grant select on public.bi_operational_capacity to authenticated;
commit;